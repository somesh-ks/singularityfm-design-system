/**
 * Builds the machine-readable design system an agent reads instead of the stylesheets:
 * tokens/system.json (every token and part, with the facts derived from the code) and
 * tokens/llms.txt (the one-page index), from the package's own files alone (DS-2): no app's
 * stylesheets, sources or bespoke list. Where an app uses a part is that app's report.
 * `npm run system` writes both; system.test.ts fails when either is stale.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  aliasTarget,
  cssName,
  declarationsFor,
  hexFor,
  loadTokens,
  type Token,
  type TokenDocument,
} from "../buildTokens.js";
import { renderLlmsFull, renderPartPage } from "./pages.js";
import { PARTS } from "./parts.js";
import { LLMS_FULL_PATH, LLMS_PATH, PACKAGE, PARTS_DIR, SYSTEM_PATH } from "./paths.js";
import { propsTable } from "./props.js";
import type { Component, Part, PartSource, System, SystemToken } from "./types.js";
import { usageComment } from "./usage.js";

/** Paths in the file are repo paths, as a part's `files` are. */
const ROOT = resolve(PACKAGE, "../..");

const GENERATED = "GENERATED by scripts/system/build.ts (npm run system). Do not edit.";

const posix = (path: string): string => path.split("\\").join("/");

const escapeRegex = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** A rule that is about the class itself: some selector of its list begins with `.name`, or with `tag.name`. */
const ruleOf = (name: string): RegExp =>
  new RegExp(`(?:^|,)\\s*(?:[a-z][\\w-]*)?\\.${escapeRegex(name)}(?![\\w-])`);

interface Stylesheet {
  file: string;
  rules: { selector: string; body: string }[];
}

function readStylesheets(): Stylesheet[] {
  const dir = join(PACKAGE, "styles");
  // By name: a part's usage is the first sheet's comment.
  return readdirSync(dir)
    .filter((name) => name.endsWith(".css") && name !== "tokens.css")
    .sort()
    .map((name) => {
      const path = join(dir, name);
      const file = posix(relative(ROOT, path));
      const css = readFileSync(path, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
      const rules = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(
        ([, selector = "", body = ""]) => ({
          selector: selector.trim(),
          body,
        }),
      );
      return { file, rules };
    });
}

/** The semantic and component custom properties, to keep a part's token list to the reusable ones. */
function reusableTokenNames(doc: TokenDocument): Set<string> {
  return new Set(
    doc.tokens.filter((token) => token.tier !== "primitive").map((token) => cssName(token.path)),
  );
}

const MANIFEST = JSON.parse(readFileSync(join(PACKAGE, "package.json"), "utf8")) as {
  name: string;
  exports: Record<string, string>;
};

/**
 * The import specifiers of a part's source files, read from the exports map so a renamed export
 * cannot leave the lookup naming one that does not resolve. The deprecated `.astro` paths are left out.
 * A module reached only through the `./*` wildcard (a behaviour or store file) is named when the
 * part's markup calls one of its exports, as Toast's `showToast(...)` calls toastStore's.
 */
function importsOf(files: string[] | undefined, markup: string | undefined): string[] {
  const exports = Object.entries(MANIFEST.exports).filter(([name]) => !name.endsWith(".astro"));
  const specifiers = (files ?? []).flatMap((file) => {
    const target = `./${posix(relative(PACKAGE, join(ROOT, file)))}`;
    const exact = exports.find(([, path]) => path === target)?.[0];
    if (exact) return [`${MANIFEST.name}/${exact.slice(2)}`];
    for (const [name, path] of exports) {
      const [head = "", tail] = path.split("*");
      if (tail === undefined || !target.startsWith(head) || !target.endsWith(tail)) continue;
      const stem = target.slice(head.length, target.length - tail.length);
      const called = [
        ...readFileSync(join(ROOT, file), "utf8").matchAll(/^export (?:function|const) (\w+)/gm),
      ].some(([, exported]) => new RegExp(`\\b${exported}\\(`).test(markup ?? ""));
      return called ? [`${MANIFEST.name}/${name.slice(2).replace("*", stem)}`] : [];
    }
    return [];
  });
  return [...new Set(specifiers)];
}

/** Each union of string literals the sources export by name: ButtonVariant -> filled, tonal, text. */
function stringUnions(): Map<string, string[]> {
  const unions = new Map<string, string[]>();
  const src = join(PACKAGE, "src");
  for (const file of readdirSync(src).filter((name) => /\.(ts|tsx)$/.test(name)))
    for (const [, name = "", body = ""] of readFileSync(join(src, file), "utf8").matchAll(
      /^export type (\w+) =\s*((?:\|?\s*"[^"]*"\s*)+);/gm,
    ))
      unions.set(
        name,
        [...body.matchAll(/"([^"]*)"/g)].map(([, value = ""]) => value),
      );
  return unions;
}

/**
 * Every component the exports map names, with its props read from its source. An .astro path kept
 * beside a .tsx (DS-3) is the same component, so the map's non-.astro name is the one listed.
 */
function components(): Component[] {
  const listed = new Map<string, Component>();
  const unions = stringUnions();
  for (const [name, path] of Object.entries(MANIFEST.exports)) {
    if (name.endsWith(".astro") || name.includes("*") || !/^\.\/src\/\w+\.(tsx|astro)$/.test(path))
      continue;
    const file = posix(relative(ROOT, join(PACKAGE, path)));
    if (listed.has(file)) continue;
    const { rows, element } = propsTable(readFileSync(join(ROOT, file), "utf8"));
    listed.set(file, {
      name: name.slice(2),
      import: `${MANIFEST.name}/${name.slice(2)}`,
      file,
      props: rows.map((row) => {
        const values = unions.get(row.type);
        return values ? { ...row, values } : row;
      }),
      ...(element ? { element } : {}),
    });
  }
  return [...listed.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function derive(source: PartSource, sheets: Stylesheet[], reusable: Set<string>): Part {
  const rulePatterns = source.classes.map(ruleOf);
  const styles = new Set<string>();
  const tokens = new Set<string>();
  for (const sheet of sheets)
    for (const rule of sheet.rules) {
      if (!rulePatterns.some((pattern) => pattern.test(rule.selector))) continue;
      styles.add(sheet.file);
      for (const [, name = ""] of rule.body.matchAll(/var\(\s*(--[\w-]+)/g))
        if (reusable.has(name)) tokens.add(name);
    }
  let usage = "";
  for (const file of styles) {
    usage = usageComment(file, `.${source.classes[0]}`, ROOT);
    if (usage) break;
  }
  return {
    ...source,
    imports: importsOf(source.files, source.markup),
    styles: [...styles].sort(),
    usage,
    tokens: [...tokens].sort(),
  };
}

/** A haptic is read by script, so it is named `haptic-open`, never as a custom property that does not exist. */
function hapticRecord(token: Token): SystemToken {
  const intent = token.tier === "semantic";
  const target = aliasTarget(token.value);
  const value = token.value;
  let light = target ? target.replace("primitive.haptic.", "pattern ") : "";
  if (!target && typeof value === "object" && value !== null && !Array.isArray(value)) {
    const ios = value.ios as { ticks: number; gap_ms: number };
    light =
      `android ${(value.android as number[]).join(" ") || "nothing"} ms; ` +
      `iphone ${ios.ticks} tick${ios.ticks === 1 ? "" : "s"}${ios.gap_ms ? `, ${ios.gap_ms} ms apart` : ""}`;
  }
  const record: SystemToken = {
    name: `haptic-${intent ? "" : "pattern-"}${token.path[token.path.length - 1]}`,
    tier: token.tier,
    type: token.type,
    light,
  };
  if (token.description) record.role = token.description;
  return record;
}

function tokenRecord(token: Token, doc: TokenDocument): SystemToken {
  if (token.type === "singularity-haptic") return hapticRecord(token);
  const render = (value: Token["value"]): string => {
    const declarations = declarationsFor(token, value, doc);
    const [first] = declarations;
    if (declarations.length === 1 && first) return first.value;
    const base = cssName(token.path);
    return declarations
      .map((declaration) => `${declaration.name.slice(base.length + 1)}: ${declaration.value}`)
      .join("; ");
  };
  const record: SystemToken = {
    name: cssName(token.path),
    tier: token.tier,
    type: token.type,
    light: render(token.value),
  };
  if (token.description) record.role = token.description;
  if (token.dark !== undefined) record.dark = render(token.dark);
  if (token.reducedMotion) record.reducedMotion = token.reducedMotion;
  // A translucent color has no single hex: the alpha would be dropped and an opaque value published.
  const translucent = [record.light, record.dark].some((value) => value?.includes(" / "));
  if (token.type === "color" && !translucent) {
    try {
      record.hex = {
        light: hexFor(doc, token.dotPath, "light"),
        dark: hexFor(doc, token.dotPath, "dark"),
      };
    } catch {
      // A translucent or non-literal color has no single hex.
    }
  }
  return record;
}

/**
 * Every custom property the package's stylesheets declare that is not a token's own name: a type
 * role's parts (`--text-label-size`), the safe-area insets, the ghost state pair a container sets.
 * The unknown-property rule (rules/index.ts) knows a read of one of these as the library's.
 */
function declaredProperties(tokens: SystemToken[]): string[] {
  const named = new Set(tokens.map((token) => token.name));
  const dir = join(PACKAGE, "styles");
  const declared = readdirSync(dir)
    .filter((name) => name.endsWith(".css"))
    .flatMap((name) => [
      ...readFileSync(join(dir, name), "utf8")
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .matchAll(/(?:@property\s+|[{;\s])(--[\w-]+)\s*[:{]/g),
    ])
    .map((match) => match[1] ?? "")
    .filter((name) => !named.has(name));
  return [...new Set(declared)].sort();
}

export function buildSystem(): System {
  const doc = loadTokens();
  const sheets = readStylesheets();
  const reusable = reusableTokenNames(doc);
  const tokens = doc.tokens.map((token) => tokenRecord(token, doc));
  return {
    generated: GENERATED,
    parts: PARTS.map((part) => derive(part, sheets, reusable)),
    components: components(),
    tokens,
    properties: declaredProperties(tokens),
  };
}

/** A role's first clause: its sentence up to a colon or a semicolon, where the examples start. */
const firstSentence = (text: string, limit: number): string => {
  const sentence =
    (text.replace(/\s+/g, " ").split(/(?<=[.!?])\s/)[0] ?? "").split(/[:;]\s/)[0] ?? "";
  return sentence.length > limit ? `${sentence.slice(0, limit - 1).trimEnd()}…` : sentence;
};

/** The one-page index: every part in a line, the color roles, the scales. Read this first. */
export function renderLlms(system: System): string {
  const lines: string[] = [
    "# Singularity design system",
    "",
    "> Components, tokens and rules for Singularity apps (`@singularityfm/design-system`). Pick a part here before writing a class or a value; a part that fits is used as it is, none fits means ask the owner. Never invent a control class.",
    "",
    `<!-- ${GENERATED} -->`,
    'Ask `ds find "<need>"`, `ds part <id>` or `ds token <words>`, not this whole file (`pnpm exec ds` in an app, `pnpm run ds` here). Rules for an app: AGENTS.md. All pages in one file: llms-full.txt. Data: system.json.',
    "",
    "## Parts",
    "An id links to its page (import, markup, props). What it is. Use: when. Not: situation → part instead.",
  ];
  for (const part of system.parts) {
    // One case each: the page holds the rest, so the index keeps room under its budget.
    const use = part.when[0] ?? "";
    const not = (part.not ?? [])
      .slice(0, 1)
      .map((item) => `${item.when} → ${item.use}`)
      .join("; ");
    const trial = (part.experimental ?? []).map((item) => item.option).join(", ");
    lines.push(
      `- [${part.id}](parts/${part.id}.md): ${part.summary} Use: ${use}.${not ? ` Not: ${not}.` : ""}${trial ? ` Experimental: ${trial}.` : ""}`,
    );
  }
  lines.push(
    "",
    "## Color roles",
    "Components read only these (never a hex, never a primitive color).",
  );
  // A tone's tinted background is the tone's name plus -subtle: one line names them, not one each.
  const colors = system.tokens.filter(
    (token) => token.tier === "semantic" && token.type === "color",
  );
  const subtle = colors.filter((token) =>
    colors.some((base) => token.name === `${base.name}-subtle`),
  );
  for (const token of colors)
    if (!subtle.includes(token))
      lines.push(
        token.role ? `- ${token.name}: ${firstSentence(token.role, 72)}` : `- ${token.name}`,
      );
  if (subtle.length > 0)
    lines.push(
      `- <tone>-subtle for ${subtle.map((token) => token.name.replace(/^--color-|-subtle$/g, "")).join(", ")}: the tone's tinted background`,
    );
  // A fill's hover and press are derived colours (D317): one line names them, not 26.
  const stated = new Set(
    system.tokens
      .filter((token) => token.tier === "semantic" && token.type === "singularity-state-color")
      .map((token) => token.name.replace(/-(hover|pressed)$/, "")),
  );
  if (stated.size > 0)
    lines.push(
      `- --color-<fill>-hover and -pressed for ${[...stated].map((name) => name.replace(/^--color-/, "")).join(", ")}: its state fills`,
    );
  lines.push("", "## Scales", "Read directly by components.");
  const scales = ["space", "radius", "stroke", "duration", "ease"];
  for (const scale of scales) {
    // Corners are read through the semantic `--shape-*` scale, which a style redraws; only the
    // round pill is read as a primitive.
    const prefix = `--${scale}-`;
    const items = system.tokens
      .filter(
        (token) =>
          token.tier === "primitive" &&
          token.name.startsWith(prefix) &&
          (scale !== "radius" || token.name === "--radius-round") &&
          // The Avatar's own animation times: it plays them, a page never reads them.
          !token.name.startsWith("--duration-avatar-"),
      )
      .map((token) => {
        const name = token.name.slice(prefix.length);
        return token.light.length > 24 ? name : `${name} ${token.light}`;
      });
    if (items.length > 0) lines.push(`- ${prefix}{${items.join(", ")}}`);
    if (scale === "radius")
      lines.push("- --shape-{xs, sm, md, lg, xl, sheet, 2xl}: corners, a style redraws them");
  }
  const groups = new Set<string>();
  for (const token of system.tokens)
    if (token.tier === "component") {
      const group = token.name.split("-")[2] ?? "";
      groups.add(group);
    }
  lines.push(
    "",
    "## Component tokens",
    `Sizes per part: ${[...groups].join(", ")}. List one with \`ds token <group>\`.`,
    "",
  );
  return lines.join("\n");
}

export function renderSystemJson(system: System): string {
  return `${JSON.stringify(system, null, 2)}\n`;
}

/** Every generated file and the text the code builds for each: the index, the data, a page per part. */
export function systemFiles(): [path: string, text: string][] {
  const system = buildSystem();
  const llms = renderLlms(system);
  return [
    [SYSTEM_PATH, renderSystemJson(system)],
    [LLMS_PATH, llms],
    [LLMS_FULL_PATH, renderLlmsFull(system, llms)],
    ...system.parts.map((part): [string, string] => [
      join(PARTS_DIR, `${part.id}.md`),
      renderPartPage(part, system.components),
    ]),
  ];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Built before anything is removed, so a throw leaves the old files in place.
  const files = systemFiles();
  // A renamed or retired part leaves no page behind.
  rmSync(PARTS_DIR, { recursive: true, force: true });
  mkdirSync(PARTS_DIR, { recursive: true });
  let pages = 0;
  for (const [path, text] of files) {
    writeFileSync(path, text, "utf8");
    if (path.startsWith(PARTS_DIR)) pages++;
    else console.log(`Wrote ${relative(ROOT, path)} (${Buffer.byteLength(text)} bytes)`);
  }
  console.log(`Wrote ${pages} part pages to ${relative(ROOT, PARTS_DIR)}`);
}
